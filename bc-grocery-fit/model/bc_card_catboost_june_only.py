def make_samples(monthly, input_months, target_month):
    periods = [
        pd.Period(month, freq="M")
        for month in input_months + [target_month]
    ]
    if any(periods[i] + 1 != periods[i + 1] for i in range(3)):
        raise ValueError("입력월과 목표월이 연속적이지 않습니다.")

    metric_cols = [
        c for c in monthly.columns
        if c not in GROUP_COLS + ["STRD_YYMM"]
    ]

    merged = None

    for month, lag in zip(input_months, ["lag3", "lag2", "lag1"]):
        part = monthly.loc[
            monthly["STRD_YYMM"].eq(month),
            GROUP_COLS + metric_cols,
        ].copy()

        part = part.rename(columns={
            c: f"{c}_{lag}" for c in metric_cols
        })

        if merged is None:
            merged = part
        else:
            merged = merged.merge(
                part,
                on=GROUP_COLS,
                how="inner",
                validate="one_to_one",
            )

    target = monthly.loc[
        monthly["STRD_YYMM"].eq(target_month),
        GROUP_COLS + metric_cols,
    ].copy()

    target = target.rename(columns={
        c: f"target_{c}" for c in metric_cols
    })

    sample = merged.merge(
        target,
        on=GROUP_COLS,
        how="inner",
        validate="one_to_one",
    )

    for lag in ["lag3", "lag2", "lag1"]:
        sample[f"log1p_total_amt_{lag}"] = np.log1p(
            sample[f"total_amt_{lag}"]
        )
        sample[f"log1p_total_cnt_{lag}"] = np.log1p(
            sample[f"total_cnt_{lag}"]
        )

        for c in CHANNELS:
            sample[f"log1p_avg_ticket_{c}_{lag}"] = np.log1p(
                sample[f"avg_ticket_{c}_{lag}"]
            )

    # 과거 변화는 입력 피처로만 사용.
    # 예측 정답은 여전히 '다음 달 비중 자체'.
    for c in CHANNELS:
        sample[f"delta1_share_amt_{c}"] = (
            sample[f"share_amt_{c}_lag1"]
            - sample[f"share_amt_{c}_lag2"]
        )
        sample[f"delta2_share_amt_{c}"] = (
            sample[f"share_amt_{c}_lag1"]
            - sample[f"share_amt_{c}_lag3"]
        )

    sample["input_start_month"] = input_months[0]
    sample["input_end_month"] = input_months[-1]
    sample["target_month"] = target_month

    return sample.sort_values(GROUP_COLS).reset_index(drop=True)


def get_feature_columns():
    features = CAT_COLS.copy()


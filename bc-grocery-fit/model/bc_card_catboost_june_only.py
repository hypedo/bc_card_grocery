def make_x(frame):
    x = frame[FEATURE_COLS].copy()

    for c in CAT_COLS:
        x[c] = x[c].astype(str)

    if x.isna().any().any():
        raise ValueError("모델 입력에 누락값이 있습니다.")

    numeric_cols = [c for c in FEATURE_COLS if c not in CAT_COLS]
    if not np.isfinite(x[numeric_cols].to_numpy(dtype=float)).all():
        raise ValueError("모델 입력에 무한대 등 비정상 값이 있습니다.")

    return x.reset_index(drop=True)


def last_share(frame):
    return frame[
        [f"share_amt_{c}_lag1" for c in CHANNELS]
    ].to_numpy(dtype=float)


def three_month_share(frame):
    amounts = np.column_stack([
        sum(
            frame[f"amt_{c}_{lag}"].to_numpy(dtype=float)
            for lag in ["lag3", "lag2", "lag1"]
        )
        for c in CHANNELS
    ])

    totals = amounts.sum(axis=1, keepdims=True)
    assert np.all(totals > 0)
    return amounts / totals


def normalize_prediction(raw, fallback):
    clipped = np.clip(raw, 0.0, 1.0)
    totals = clipped.sum(axis=1, keepdims=True)

    valid = totals[:, 0] > 0
    prediction = fallback.copy()
    prediction[valid] = clipped[valid] / totals[valid]

    assert np.isfinite(prediction).all()
    assert np.allclose(prediction.sum(axis=1), 1.0)
    return prediction


def metrics(actual, prediction):
    error = prediction - actual
    return {
        "mae_pp": float(np.mean(np.abs(error)) * 100),
        "rmse_pp": float(np.sqrt(np.mean(error ** 2)) * 100),
        "n_samples": len(actual),
    }



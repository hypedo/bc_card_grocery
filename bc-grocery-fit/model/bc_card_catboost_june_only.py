history = []
seen = set()


def evaluate_candidate(params, stage):
    key = tuple(sorted(params.items()))
    if key in seen:
        return

    raw = np.zeros_like(Y_va)
    trees = []

    for j, c in enumerate(CHANNELS):
        model = CatBoostRegressor(**{
            **COMMON_PARAMS,
            **params,
        })

        model.fit(
            X_tr,
            Y_tr[:, j],
            cat_features=CAT_COLS,
            eval_set=(X_va, Y_va[:, j]),
            early_stopping_rounds=PATIENCE,
            use_best_model=True,
        )

        raw[:, j] = model.predict(X_va)
        trees.append(int(model.tree_count_))

    prediction = normalize_prediction(raw, va_last)
    score = metrics(Y_va, prediction)["mae_pp"]

    history.append({
        "stage": stage,
        "params": params.copy(),
        "trees": trees,
        "validation_mae_pp": score,
        "validation_prediction": prediction,
    })
    seen.add(key)

    print(
        f"[{stage} #{len(history)}] "
        f"MAE={score:.4f}%p | {params} | trees={trees}",
        flush=True,
    )


def search_table():
    return pd.DataFrame([
        {
            "stage": r["stage"],
            **r["params"],
            "validation_mae_pp": r["validation_mae_pp"],
            "trees_mart": r["trees"][0],
            "trees_super": r["trees"][1],
            "trees_cvs": r["trees"][2],
        }
        for r in history
    ]).sort_values("validation_mae_pp").reset_index(drop=True)


